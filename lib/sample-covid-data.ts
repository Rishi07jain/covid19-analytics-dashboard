// Generate date range for time series
function generateDates(days: number): string[] {
  const dates: string[] = []
  const endDate = new Date("2023-03-09")
  for (let i = days - 1; i >= 0; i--) {
    const date = new Date(endDate)
    date.setDate(date.getDate() - i)
    dates.push(date.toISOString().split("T")[0])
  }
  return dates
}

// Generate realistic time series data
function generateTimeSeries(
  final: number,
  days: number,
  growthPattern: "exponential" | "sigmoid" = "sigmoid",
): number[] {
  const values: number[] = []
  for (let i = 0; i < days; i++) {
    const progress = i / (days - 1)
    let value: number
    if (growthPattern === "sigmoid") {
      // Sigmoid curve for realistic pandemic growth
      const sigmoid = 1 / (1 + Math.exp(-12 * (progress - 0.3)))
      value = Math.round(final * sigmoid)
    } else {
      value = Math.round(final * Math.pow(progress, 2))
    }
    values.push(Math.max(0, value))
  }
  return values
}

